var update = flag.Bool("update", false, "rewrite the committed fixtures under tests/testdata/grpc")

const testdata = "../../tests/testdata/grpc"

// TestCommittedFixturesMatchGenerator fails when the descriptor changed and
// the files were not regenerated: go test ./internal/grpcfixture -update.
//
// The set is compared as a message, not as bytes, so an encoder that orders
// fields differently does not make it stale.
func TestCommittedFixturesMatchGenerator(t *testing.T) {
	setPath := filepath.Join(testdata, "users.binpb")
	protoPath := filepath.Join(testdata, "users.proto")
	if *update {
		if err := os.MkdirAll(testdata, 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(setPath, SetBytes(), 0o644); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(protoPath, []byte(render(UsersFile())), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}

	raw, err := os.ReadFile(setPath)
	if err != nil {
		t.Fatalf("%v; run: go test ./internal/grpcfixture -update", err)
	}
	got := &descriptorpb.FileDescriptorSet{}
	if err := proto.Unmarshal(raw, got); err != nil {
		t.Fatal(err)
	}
	if !proto.Equal(got, Set()) {
		t.Errorf("%s is stale; run: go test ./internal/grpcfixture -update", setPath)
	}

	src, err := os.ReadFile(protoPath)
	if err != nil {
		t.Fatalf("%v; run: go test ./internal/grpcfixture -update", err)
	}
	if string(src) != render(UsersFile()) {
		t.Errorf("%s is stale; run: go test ./internal/grpcfixture -update", protoPath)
	}
}

// TestSetResolves: the set loads the way the grpc-server resource loads it,
// with every service and method the tests name.
func TestSetResolves(t *testing.T) {
	path := filepath.Join(t.TempDir(), "users.binpb")
	if err := os.WriteFile(path, SetBytes(), 0o644); err != nil {
		t.Fatal(err)
	}
	schema, err := grpcschema.LoadDescriptorSets(path)
	if err != nil {
		t.Fatal(err)
	}
	for _, m := range []string{"GetUser", "ListUsers", "WatchUsers", "ImportUsers"} {
		if _, err := schema.FindMethod(Service + "/" + m); err != nil {
			t.Error(err)
		}
	}
	md, _ := schema.FindMethod(Service + "/WatchUsers")
	if !md.IsStreamingServer() || md.IsStreamingClient() {
		t.Error("WatchUsers must be server-streaming")
	}
	if f := md.Output().Fields().ByName("created_at"); f == nil || f.JSONName() != "createdAt" {
		t.Errorf("created_at should have json name createdAt, got %v", f)
	}
}

// render prints the subset of proto3 users.proto uses, so the committed
// .proto is what a person reads and the set is what tomato loads.
func render(fd *descriptorpb.FileDescriptorProto) string {
	var b strings.Builder
	b.WriteString("// Generated by `go test ./internal/grpcfixture -update` from internal/grpcfixture; do not edit.\n")
	b.WriteString("// users.binpb is the same file as a FileDescriptorSet, as `buf build -o users.binpb` writes it.\n\n")
	fmt.Fprintf(&b, "syntax = %q;\n\npackage %s;\n\n", fd.GetSyntax(), fd.GetPackage())
	for _, dep := range fd.GetDependency() {
		fmt.Fprintf(&b, "import %q;\n", dep)
	}
	typeName := func(name string) string {
		return strings.TrimPrefix(strings.TrimPrefix(name, "."), fd.GetPackage()+".")
	}
	for _, sd := range fd.GetService() {
		fmt.Fprintf(&b, "\nservice %s {\n", sd.GetName())
		for _, m := range sd.GetMethod() {
			in, out := typeName(m.GetInputType()), typeName(m.GetOutputType())
			if m.GetClientStreaming() {
				in = "stream " + in
			}
			if m.GetServerStreaming() {
				out = "stream " + out
			}
			fmt.Fprintf(&b, "  rpc %s(%s) returns (%s);\n", m.GetName(), in, out)
		}
		b.WriteString("}\n")
	}
	for _, ed := range fd.GetEnumType() {
		fmt.Fprintf(&b, "\nenum %s {\n", ed.GetName())
		for _, v := range ed.GetValue() {
			fmt.Fprintf(&b, "  %s = %d;\n", v.GetName(), v.GetNumber())
		}
		b.WriteString("}\n")
	}
	for _, md := range fd.GetMessageType() {
		fmt.Fprintf(&b, "\nmessage %s {\n", md.GetName())
		for _, f := range md.GetField() {
			typ := strings.ToLower(strings.TrimPrefix(f.GetType().String(), "TYPE_"))
			if f.GetTypeName() != "" {
				typ = typeName(f.GetTypeName())
			}
			if f.GetLabel() == descriptorpb.FieldDescriptorProto_LABEL_REPEATED {
				typ = "repeated " + typ
			}
			fmt.Fprintf(&b, "  %s %s = %d;\n", typ, f.GetName(), f.GetNumber())
		}
		b.WriteString("}\n")
	}
	return b.String()
}
